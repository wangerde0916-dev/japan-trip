import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Resolve from this script so the command also works from another directory.
const sourceURL = new URL('../trip-data.json', import.meta.url);
const outputURL = new URL('../data.js', import.meta.url);
const source = await readFile(sourceURL, 'utf8');

// Validate before writing, without changing, reordering, or replacing trip data.
JSON.parse(source);
await writeFile(outputURL, `// Generated by scripts/build-data.mjs. Edit trip-data.json, then rebuild.\nwindow.TRIP_DATA = ${source}\n;\n`, 'utf8');
console.log(`Generated ${fileURLToPath(outputURL)}`);

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Resolve from this script so the command also works from another directory.
const outputURL = new URL('../data.js', import.meta.url);
const inputs = [['trip-data.json', 'TRIP_DATA'], ['trip-data-plus.json', 'TRIP_DATA_PLUS']];
const sources = await Promise.all(inputs.map(async ([file, name]) => {
  const source = await readFile(new URL(`../${file}`, import.meta.url), 'utf8');
  // Validate both sources before touching the output. Preserve the original text.
  JSON.parse(source);
  return `window.${name} = ${source}\n;\n`;
}));

// Validate before writing, without changing, reordering, or replacing trip data.
await writeFile(outputURL, `// Generated by scripts/build-data.mjs from trip-data.json and trip-data-plus.json.\n${sources.join('\n')}`, 'utf8');
console.log(`Generated ${fileURLToPath(outputURL)}`);
